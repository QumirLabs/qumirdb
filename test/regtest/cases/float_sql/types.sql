-- REAL, FLOAT4 and FLOAT(1..24) are 4 bytes; FLOAT, FLOAT(25..53), FLOAT8 and DOUBLE PRECISION are 8.
SELECT id, CAST(d AS REAL) AS r, CAST(d AS FLOAT4) AS r4, CAST(d AS FLOAT(24)) AS r24, d::real AS rc,
  CAST(d AS FLOAT) AS f, CAST(d AS FLOAT(25)) AS f25, CAST(d AS FLOAT8) AS f8, CAST(d AS DOUBLE PRECISION) AS dp
FROM t ORDER BY id;
