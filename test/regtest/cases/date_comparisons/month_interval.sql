SELECT CAST(CAST(d AS DATE) AS VARCHAR) AS iso,
       CAST(CAST(d + INTERVAL '1' MONTH AS DATE) AS VARCHAR) AS p1m,
       CAST(CAST(d - INTERVAL '1' MONTH AS DATE) AS VARCHAR) AS m1m,
       CAST(CAST(d + INTERVAL '-3' MONTH AS DATE) AS VARCHAR) AS m3m,
       CAST(CAST(d + INTERVAL '25' MONTH AS DATE) AS VARCHAR) AS p25m,
       CAST(CAST(d + INTERVAL '1' YEAR AS DATE) AS VARCHAR) AS p1y,
       CAST(CAST(d - INTERVAL '2' YEAR AS DATE) AS VARCHAR) AS m2y,
       CAST(CAST(d + INTERVAL '10' DAY AS DATE) AS VARCHAR) AS p10d,
       CAST(CAST(DATE '1997-07-01' + INTERVAL '3' MONTH AS DATE) AS VARCHAR) AS q4_bound,
       d >= DATE '1997-07-01' AND d < DATE '1997-07-01' + INTERVAL '3' MONTH AS in_q4
FROM month_edges ORDER BY d;
